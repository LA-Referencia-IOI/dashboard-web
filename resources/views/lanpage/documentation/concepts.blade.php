        <h3>dARK</h3>
        <section id="what-is-dark">
            <h4>What is dARK?</h4>
            <p class="text-justify">
                The decentralized ARK identifier assignment system, which we call dARK, employs an approach that allows multiple institutions to collaboratively manage 
                their persistent ARK identifier system using a common decentralized infrastructure based on nodes of a blockchain consortium network. In this way, 
                the data is not owned, stored, or controlled by a single organization, but by all participants in the network. Considering that dARK users will 
                participate in a well-organized blockchain consortium network, the PID data will be replicated securely, reliably, audibly, and accessibly across all 
                nodes of this network. Even if an institution disappears, the stored data will persist in the remaining nodes of the network. Furthermore, given the
                blockchain consortium network, the cost of storing and managing the PID data will be low. It is estimated that each dARK identifier assignment will 
                require 12KB of disk storage. Additionally, a standard server instance has been designed to run the decentralized application (for example, in the 
                experimental environment, a virtual machine with 4 Xeon cores, 16GB of RAM, and 30GB of storage was used).
            </p>
        </section>

        <section id="dark-identifiers">
            <h4>dARK Identifiers</h4>
            <p class="text-justify">
            To enable the decentralization of the ARK, first, we have to extend the ARK identifier to be compatible
            with the new organizational structure of the consortium of institutions that will use the dARK. Thus the
            proposed extension is fully compatible with ARK identifier assigning rules. This provides an automatic
            compatibility with standard ARK interoperability protocols. In this structure the ARK Alliance [34] is
            able to issue just a unique NAAN prefix to an entire blockchain consortium network. For instance, in
            Brazil, a consortium should be founded by a federal governmental research institute related to science
            and technology, the Instituto Brasileiro de Informac ̧  ̃ao em Ciência e Tecnologia (IBICT)
            </p>
            <p class="text-justify">
            In order to decentralize the ARK identifiers, the dARK system was designed with PID management
            capabilities for the curators of each institution that composes the consortium. To accomplish the aforemen-
            tioned goal, two new elements were incorporated into the shoulder of the ARK identifier, the Decentralized
            Name Assigning Authority (DNA) and Section Name Authority (SNA).
            </p>
            <p class="text-justify">
            The DNA is a shoulder prefix employed to identify which consortium member is responsible for a
            specific PID assignment. DNA is similar to a NAAN; however, it identifies the institution (authority)
            responsible within the consortium context. The SNA is used to assign a section authority within an
            institution. For example, a university could indicate a curator for different libraries by assigning different
            SNAs for each collection. Figure 1 presents an example of an assigned identifier
