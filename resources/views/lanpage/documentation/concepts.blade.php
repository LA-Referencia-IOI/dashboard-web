        <h3>ARK</h3>
        <section id="what-is-ark">
            <h4>What is ARK?</h4>
            <p class="text-justify">
                The Archival Resource Key (ARK) is an open PID system that provides reliable references for information objects. 
                According to Kunze and Bermès (2008) in their work "The ARK Identifier Scheme," Archival Resource Keys (ARKs) are a 
                flexible and low-cost alternative for assigning persistent identifiers. Any organization has the possibility to create an 
                unlimited number of identifiers using a flexible metadata scheme. However, most ARK implementations rely on internal solutions
                that are isolated from each other, leading to issues such as PID duplication, cost inefficiency, and low fault tolerance.
            </p>
            <p> To be used in various applications mentioned above, the ARK was conceived to be generic. Furthermore,
                the fundamental design of ARK are:
            </p>
            <li>
                High-density identifiers, permitting opaque and shorter identifiers;
            </li>
            <li>
                Self-sufficiency, using Noid (Nice Opaque Identifiers) and a simple HTTP Server, it is possible to
            execute an ARKs servers;
            </li>
            <li>
                Flexible metadata schema;
            </li>
            <li>
                Able to provide identifiers without metadata;
            </li>
            <li>
                Capable of assigning additional identifiers (e.g., a DOI) to an object;
            </li>
            <li>
                Provide a query mechanism when resolving the identifiers;
            </li>
            <li>
                Provide global resolvability (Name-to-Thing resolver);
            </li>
            <li>
                Affordable, there are no fees to assign ARK PIDs.
            </li>
            <p class="text-justify">
            These designs were incorporated in ARK and distributed in two main components; the ARK identifiers
            and the ARK system architecture. The core concept of the ARK identifier is that the identifier attribution
            process was created considering a self-sufficient away. The ARK does not need a central authority to
            generate a new identifier, mainly because the ARK does not need external information to assign a new
            unique identifier.

            To enable self-sufficient identifiers, the ARK incorporates Name Assigning Authority Numbers (NAANs)
            identification in the object identifier. An organization (e.g., an university) must be registered within the
            ARK Alliance to generate an ARK identifier. In this registration process, the organization will receive a
            NAAN identification, e.g., the Instituto Brasileiro de Informação em Ciência e Tecnologia (IBICT) has
            the NAAN 80033. The NAAN is used as the prefix of the ARK identifier, making it impossible for any
            other organization to generate IDs with this prefix.
            A typical ARK identifier comprises four parts, NAAM, shoulder, blade, and tip. Figure 1 represents
            hypothetical ARK identifier
            </p>
            <p class="text-justify">
            The ark:/, designates the schema of the identifiers. The 80033 is the NAAM responsible for the identifier.
            The shoulder (in Figure 1 the shoulder is tqbmb3) designates the organization unit (e.g., university
            department) responsible for the identifier, defining sub-namespace. Unique shoulders guarantee that names
            within the sub-namespace will also be unique outside of it, and the unit need only focus on creating the
            rest of the key in a unique way. The blade (kh97gh8) is a unique id generated by the unit. Finally, the
            tip (w) is the verification digit of all parts of the ARK identifier.
            </p>







